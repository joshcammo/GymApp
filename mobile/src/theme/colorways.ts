/**
 * Colorway definitions — each id has a light and dark token set matching
 * the ColorTokens shape below. Generated with a shared HSL formula (see
 * scratchpad contrast/generate scripts from the theming session) so every
 * pair clears WCAG contrast (text/textSub vs bg/card >= 4.5:1, primary/cold
 * used as icon or large text vs bg/card >= 3:1) and every colorway's `cold`
 * heatmap accent sits well clear of its own `primary` hue (>= 60deg apart)
 * so the muscle-group heatmap's over/under diverging pair never collides,
 * even for the colorways whose primary is itself blue. Ember's dark variant
 * is pinned to the exact values GymApp already shipped with, byte-for-byte,
 * so existing users see zero change unless they opt into a new colorway.
 */
